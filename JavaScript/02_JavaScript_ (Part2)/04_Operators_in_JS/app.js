//Operators:
let a = 10;
let b = 5;

// Arithmetic Operators (+, -, *, /, %, **)
console.log(a+b);       // 15
console.log(a-b);       // 5
console.log(a*b);       // 50
console.log(a/b);       // 2
console.log(a%b);       // 0
console.log(a**b);       // 100000

// Unary Operators (++, --):
console.log(a++);       // 10
console.log(++a);       // 12
console.log(a--);       // 12
console.log(--a);       // 10

// Assignment Operators (=, +=, -=, *=, /=, %= etc):
b = a;
console.log(b);       // 10
console.log(a += 2);       // 12
console.log(a -= 2);       // 10
console.log(a *= 2);       // 20 // here value of 'a' becomes 20
console.log(a /= 10);       // 2
console.log(a %= 2);       // 0
