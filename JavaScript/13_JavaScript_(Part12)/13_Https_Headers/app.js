/*

# Https Headers:
==> HTTP headers are key–value pairs that send extra 
information between client and server with every HTTP 
request and response.

They are like metadata (data about data).

--------------------------------------------------------------------------

🔑 Types of HTTP Headers:

1️⃣ Request Headers (Client → Server):
==> Tell the server what the client wants or sends.

Common ones:

Host → website domain
User-Agent → browser info
Accept → expected response format
Authorization → token / auth info
Content-Type → data type being sent

2️⃣ Response Headers (Server → Client):
==> Tell the browser how to handle the response.

Common ones:

Content-Type → response format (JSON, HTML)
Content-Length → size of response
Set-Cookie → store data in browser
Cache-Control → caching rules
Access-Control-Allow-Origin → CORS

3️⃣ Entity / Representation Headers:
==> Describe the body data.

Content-Type
Content-Encoding
Content-Language
*/

