/*
**************** Nested Array *******************

==> array of arrays, also known as 'multi-dimensional' array or 'nested' array
*/

let nums = [[2, 4], [3, 6], [4, 8]];

console.log(nums)               //output: (3) [Array(2), Array(2), Array(2)]
console.log(nums.length)        // 3
console.log(nums[0])            // (2) [2, 4]
console.log(nums[0].length)     // 2
console.log(nums[0][1])         // 4
console.log(nums[1])            // (2) [3, 6]
console.log(nums[1][1])         // 6  


