// forward loop:
for (let i = 1; i<=10; i++) {
    console.log(i)    
}

// backward loop:
for (let i = 5; i>=1; i--) {
     console.log(i);    
}


for (let i = 10; i>=1; i = i-3) {
     console.log(i)
}
